import uiautomator2 as u2
# Подключаемся к уже активному локальному ADB-транспорту
d = u2.connect() 

# Ищем элемент "Беспроводная отладка" (или "Отладка по WLAN", как в твоем скрипте)
# Если у тебя в системе пункт называется "Отладка по WLAN", замени текст в кавычках ниже
el = d(text="Беспроводная отладка") 

# Если пункт скрыт внизу, скроллим до него
if not el.exists:
    d(scrollable=True).scroll.to(text="Беспроводная отладка")

# Выводим свойства и координаты на экран
print(el.info)
