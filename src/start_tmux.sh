#!/bin/bash

# =====================================================================
# СПРАВКА ПО КОМАНДАМ TMUX (ДЛЯ УПРАВЛЕНИЯ С КЛАВИАТУРЫ):
# Все команды в tmux нажимаются через "префикс" (Ctrl + B), затем кнопка.
#
# КОРРЕКТНЫЙ ВЫХОД (ОТКЛЮЧЕНИЕ):
#   Ctrl + B, затем D     - Отключиться от сессии (оставить её в фоне)
#
# РАБОТА С ОКНАМИ (ПАНЕЛЯМИ):
#   Ctrl + B, затем "     - Разделить текущую панель по горизонтали
#   Ctrl + B, затем %     - Разделить текущую панель по вертикали
#   Ctrl + B, затем Стрелочки - Переключить фокус между панелями
#   Ctrl + B, затем Alt + Стрелочки - Изменить размер текущей панели
#   Ctrl + B, затем X     - Закрыть текущую панель (убить процесс)
#
# РАБОТА С СЕССИЯМИ ИЗ КОНСОЛИ:
#   tmux ls               - Показать список всех запущенных сессий
#   tmux attach -t имя    - Подключиться обратно к фоновой сессии
#   tmux kill-session -t имя - Полностью удалить сессию и закрыть её
# =====================================================================

# Название вашей сессии (можете изменить на любое имя)
SESSION_NAME="ollama"

# 1. Запускаем новую сессию tmux в фоновом режиме (-d) с указанным именем
tmux new-session -d -s "$SESSION_NAME"

# 2. Делим созданное окно по горизонтали (split-window -h) на две части
tmux split-window -h -t "$SESSION_NAME"

# 3. Подключаем вас к уже разделенной и настроенной сессии
tmux attach-session -t "$SESSION_NAME"
