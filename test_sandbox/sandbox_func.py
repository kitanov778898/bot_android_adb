# -----------------------------------------------------------------------------
# ВЕРСИОНИРОВАНИЕ (напоминание)
# -----------------------------------------------------------------------------
# Формат: MAJOR.MINOR.PATCH (например, 0.1.0)
# MAJOR — ломающие изменения. MINOR — новые функции без поломки. PATCH — багфиксы.
# Как менять: багфикс → PATCH, новая функция → MINOR, переписали ядро → MAJOR.
# -----------------------------------------------------------------------------
__version__ = "0.2.0"

# Получаем абсолютный путь к текущему скрипту, чтобы в логах было понятно,
# где именно выполняется скрипт (важно для Orange Pi, Termux и разных папок)
script_path = Path(__file__).resolve()
script_name = script_path.name
script_dir = script_path.parent

log_path = script_dir / "test_run.log"

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s | %(levelname)s | %(message)s",
    handlers=[logging.FileHandler(log_path, mode="a", encoding="utf-8")]
)

# Фиксируем в логе: какой файл, где лежит, какая версия
logging.info(
    f"Запущен тестовый прогон: файл={script_name}, "
    f"путь={script_dir}, версия={__version__}"
)


def test_adb_ping():
    """
    Тестовый «пинг» ADB-соединения (mock-функция).

    Эта функция не делает реального запроса к устройству — она служит
    заглушкой для проверки логики: что логи пишутся, версия видна,
    а функция возвращает понятный результат.

    Returns:
        dict: Результат теста в формате:
            {
                "status": "ok" | "warning" | "error",
                "test": "adb_ping"
            }
    """
    logging.info("Тестовый ADB-пинг выполнен")
    print(f"Версия теста: {__version__}, файл: {script_name}")
    return {"status": "ok", "test": "adb_ping"}


if __name__ == "__main__":
    # Блок if __name__ == "__main__" нужен, чтобы функция test_adb_ping()
    # запускалась только при прямом запуске файла (python sandbox_func.py),
    # а не при импорте этого файла в другой скрипт.
    test_adb_ping()

